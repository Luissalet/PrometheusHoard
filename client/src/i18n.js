export function initialLang() {
  try {
    const stored = localStorage.getItem("prometheus-lang");
    if (stored === "es" || stored === "en") return stored;
  } catch {
    // storage may be blocked; Spanish is the default
  }
  return "es";
}

export function saveLang(lang) {
  try {
    localStorage.setItem("prometheus-lang", lang);
  } catch {
    // not critical
  }
}

export function makeT(lang) {
  const index = lang === "en" ? 1 : 0;
  const fill = (entry, vars) => {
    let value = entry[index] ?? entry[0];
    if (vars) for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(v));
    return value;
  };
  const t = (key, vars) => {
    const one = vars && Number(vars.n) === 1 ? D[`${key}_one`] : undefined;
    const entry = one || D[key];
    if (entry === undefined) return key;
    return fill(entry, vars);
  };
  t.has = (key) => D[key] !== undefined;
  return t;
}

